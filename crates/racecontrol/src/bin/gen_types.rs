// crates/racecontrol/src/bin/gen_types.rs
// Phase 445 Wave 1 skeleton -- Plan 02a/02b fill in actual type + route generation.
//
// Strategy locked by Plan 00 SPIKE (Verdict A): ts-rs 12.0.1's
// TS::export_all(&Config) works in plain fn main() context (no cargo-test
// fallback needed). API name is `export_all` (not `export_all_to` as
// RESEARCH.md originally documented -- see 445-00-SPIKE.md).
//
// Wave 1 goal: the binary compiles + runs + emits a deterministic
// placeholder output. Plan 02a adds real per-type
// ts_rs::TS::export_all(&cfg) calls. Plan 02b populates ApiDoc with
// real #[utoipa::path] route annotations.
//
// Decision IDs: D-03 (gen-types binary), D-09 (output dir
// packages/shared-types/generated), Pitfall 3 (openapi module does NOT
// wire into live axum Router), Pitfall 6 (determinism harness armed).

use std::path::Path;
use utoipa::OpenApi; // provides ApiDoc::openapi() via #[derive(OpenApi)]

fn main() -> anyhow::Result<()> {
    eprintln!("gen-types: starting (Phase 445 Wave 1 skeleton)");

    // ---------------- OpenAPI emission ----------------
    // ApiDoc is defined in crates/racecontrol/src/api/openapi.rs and
    // feature-gated behind `gen-types`. For Wave 1 it has zero paths;
    // Plan 02b adds them via utoipa_axum::OpenApiRouter.
    let openapi = racecontrol_crate::api::openapi::ApiDoc::openapi();
    let yaml = serde_yaml::to_string(&openapi)?;
    let yaml_path = Path::new("docs/openapi.generated.yaml");
    if let Some(dir) = yaml_path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(yaml_path, &yaml)?;
    eprintln!(
        "gen-types: wrote {} ({} bytes)",
        yaml_path.display(),
        yaml.len()
    );

    // ---------------- ts-rs emission ----------------
    // Plan 02a will replace this block with explicit
    // TS::export_all(&cfg) calls per admin-consumed apex type, reading
    // packages/shared-types/generated/.whitelist.txt (42 names emitted
    // by Plan 00). Wave 1 emits only a placeholder index.ts so the
    // drift-check script has a file to diff.
    let gen_dir = Path::new("packages/shared-types/generated");
    std::fs::create_dir_all(gen_dir)?;
    let index_path = gen_dir.join("index.ts");
    let index_body = "// Generated by gen-types (Phase 445). DO NOT EDIT.\n\
                      // Plan 02a fills in per-type re-exports.\n\
                      export {};\n";
    std::fs::write(&index_path, index_body)?;
    eprintln!(
        "gen-types: wrote {} ({} bytes)",
        index_path.display(),
        index_body.len()
    );

    // NOTE for Plan 02a sketch (per SPIKE.md):
    //
    //     use ts_rs::{Config, TS};
    //     let cfg = Config::new().with_out_dir(gen_dir);
    //     rc_common::types::BillingSessionInfo::export_all(&cfg)?;
    //     rc_common::types::PodInfo::export_all(&cfg)?;
    //     rc_common::types::FleetHealthResponse::export_all(&cfg)?;
    //     // ... one call per apex type from .whitelist.txt

    eprintln!("gen-types: done");
    Ok(())
}
