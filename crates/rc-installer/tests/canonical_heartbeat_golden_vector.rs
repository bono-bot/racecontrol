//!
//! Recipe (= `packages/contracts` `canonicalJson()`): compact JSON, declaration-order,
//! `signature` excluded, `feature_opt_in` OPEN Record<string,boolean> keys sorted
//! (BTreeMap), `issued_at`/`valid_until` Unix-ms. Envelope `SignedLicenseHeartbeat
